"""End-to-end high-frequency alpha study.

    python examples/alpha_research.py                       # planted-alpha simulation (default)
    python examples/alpha_research.py --bookticker BTCUSDT-bookTicker-2024-03-01.zip \
                                      --aggtrades  BTCUSDT-aggTrades-2024-03-01.zip

Writes figures to docs/figures/alpha_*.png and the report to docs/ALPHA_RESULTS.md.
Every number in the report is computed by this script; nothing is hard-coded.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from quantforge.alpha import evaluation as ev
from quantforge.alpha import signals as sg
from quantforge.alpha.data import load_binance
from quantforge.alpha.market_making import simulate_market_maker
from quantforge.alpha.simulate import simulate_book

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "docs" / "figures"
FIG.mkdir(parents=True, exist_ok=True)

SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
INK, INK2, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#8a8984", "#e4e3df", "#fcfcfb"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": GRID, "axes.labelcolor": INK2, "axes.titlecolor": INK, "axes.titlesize": 12,
    "axes.titleweight": "semibold", "axes.titlelocation": "left", "axes.labelsize": 10,
    "xtick.color": INK2, "ytick.color": INK2, "xtick.labelsize": 9, "ytick.labelsize": 9,
    "axes.grid": True, "axes.axisbelow": True, "grid.color": GRID, "grid.linewidth": 0.8, "axes.spines.top": False,
    "axes.spines.right": False, "legend.frameon": False, "legend.fontsize": 9, "lines.linewidth": 2.0,
})

HORIZONS = [1, 2, 5, 10, 20, 50, 100, 200, 500]
H = 10  # forecast horizon used for the combined model (steps)


def build_signals(b):
    mid = b.mid
    return {
        "book imbalance": sg.book_imbalance(b.bid_qty, b.ask_qty),
        "order-flow imbalance (20)": sg.order_flow_imbalance(b.bid, b.ask, b.bid_qty, b.ask_qty, 20),
        "trade-flow imbalance (50)": sg.trade_flow_imbalance(b.buy_vol, b.sell_vol, 50),
        "past return (50)": sg.past_return_bps(mid, 50),
    }


def fmt(x, d=3):
    return f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bookticker")
    ap.add_argument("--aggtrades")
    ap.add_argument("--step-ms", type=int, default=100)
    ap.add_argument("--fee-bps", type=float, default=5.0, help="taker fee for the cost analysis")
    args = ap.parse_args()

    if args.bookticker:
        book = load_binance(args.bookticker, args.aggtrades, step_ms=args.step_ms)
        source = f"Binance files `{Path(args.bookticker).name}` (step {args.step_ms} ms)"
        null_book = None
    else:
        book = simulate_book(n_steps=300_000, seed=1)
        null_book = simulate_book(n_steps=300_000, beta=0, gamma=0, kappa=0, seed=2)
        source = "**simulated** order book with a planted alpha (`quantforge.alpha.simulate`, seed 1)"

    out = [f"# Alpha research report\n\nData: {source}, {len(book):,} steps.\n",
           "Generated by `python examples/alpha_research.py`. Every number below is computed, not typed.\n"]
    mid = book.mid
    sigs = build_signals(book)

    # --- 1. IC decay and the overlapping-returns trap -----------------------
    table = {name: ev.ic_decay(x, mid, HORIZONS) for name, x in sigs.items()}
    out.append("## 1. Information coefficient by horizon\n")
    out.append("| signal | " + " | ".join(f"h={h}" for h in HORIZONS) + " |")
    out.append("|---|" + "---|" * len(HORIZONS))
    for name, rows in table.items():
        out.append(f"| {name} | " + " | ".join(fmt(r["ic"]) for r in rows) + " |")
    out.append("\n**t-statistics at h = 50: naive OLS vs Newey-West** (overlapping returns)\n")
    out.append("| signal | naive t | Newey-West t | inflation |\n|---|---|---|---|")
    for name, rows in table.items():
        r = next(r for r in rows if r["horizon"] == 50)
        out.append(f"| {name} | {r['t_naive']:.1f} | {r['t_nw']:.1f} | {r['t_naive'] / r['t_nw']:.1f}x |")

    fig, ax = plt.subplots(figsize=(7.2, 4.2))
    for i, (name, rows) in enumerate(table.items()):
        ax.semilogx([r["horizon"] for r in rows], [r["ic"] for r in rows], "-o", ms=4, color=SERIES[i], label=name)
    if null_book is not None:
        nrows = ev.ic_decay(sg.trade_flow_imbalance(null_book.buy_vol, null_book.sell_vol, 50), null_book.mid, HORIZONS)
        ax.semilogx(HORIZONS, [r["ic"] for r in nrows], "--", color=MUTED, lw=1.5, label="trade-flow imb., zero-alpha market")
    ax.axhline(0, color=INK2, lw=0.8)
    ax.set_xlabel("forecast horizon (steps)")
    ax.set_ylabel("information coefficient")
    ax.set_title("IC decay: how far ahead each signal sees")
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIG / "alpha_ic_decay.png", dpi=160)
    plt.close(fig)

    # --- 2. combined alpha, walk-forward ---------------------------------------
    names = list(sigs)
    X = np.column_stack([sigs[n] for n in names])
    y = ev.forward_return_bps(mid, H)
    yhat, coefs = ev.walk_forward_ridge(X, y, horizon=H, n_folds=5, lam=1.0)
    m = np.isfinite(yhat) & np.isfinite(y)
    combo_ic = float(np.corrcoef(yhat[m], y[m])[0, 1])
    single_fc = {n: ev.walk_forward_ridge(sigs[n][:, None], y, horizon=H)[0] for n in names}
    single_r2 = {n: ev.oos_r2(y, single_fc[n]) for n in names}
    out.append(f"\n## 2. Combined alpha (ridge, 5-fold expanding walk-forward, embargo {H} steps, h = {H})\n")
    out.append("The model is `alpha_hat = mean_train(y) + sum_i w_i (x_i - mu_i) / sd_i`, re-fitted on each fold using only "
               "data that ends at least one label-horizon before the test block.\n")
    out.append("| model | out-of-sample R² |\n|---|---|")
    for n in names:
        out.append(f"| {n} alone | {single_r2[n]:.4f} |")
    out.append(f"| **combined** | **{ev.oos_r2(y, yhat):.4f}** (OOS IC {combo_ic:.3f}) |")
    out.append("\nStandardised weights by fold (stable weights are a sign the model is not over-fitted):\n")
    out.append("| fold | " + " | ".join(names) + " |\n|---|" + "---|" * len(names))
    for i, w in enumerate(coefs):
        out.append(f"| {i + 1} | " + " | ".join(f"{v:+.3f}" for v in w) + " |")

    means, _ = ev.quantile_returns(yhat, y, 10)
    fig, ax = plt.subplots(figsize=(7.2, 3.8))
    ax.bar(np.arange(1, 11), means, color=[SERIES[0] if v >= 0 else SERIES[1] for v in means], width=0.7)
    ax.axhline(0, color=INK2, lw=0.8)
    ax.set_xticks(np.arange(1, 11))
    ax.set_xlabel("decile of out-of-sample forecast")
    ax.set_ylabel(f"mean {H}-step return (bps)")
    ax.set_title("Out-of-sample forecast deciles: monotone means a real ranking")
    fig.tight_layout()
    fig.savefig(FIG / "alpha_deciles.png", dpi=160)
    plt.close(fig)

    # --- 3. costs -----------------------------------------------------------------
    out.append("\n## 3. Does it survive costs? (taker strategy, rebalanced every h steps)\n")
    out.append(f"Half-spread is paid on every trade; fee scenarios in bps of notional. The headline taker fee is {args.fee_bps} bp.\n")
    out.append("| threshold (bps) | trades | hit rate | gross bps / period | break-even fee (bps) | net bps / period @ fee |\n|---|---|---|---|---|---|")
    thresholds = [0.0, 0.25, 0.5, 1.0]
    results = {}
    for thr in thresholds:
        r = ev.taker_backtest(yhat, book.bid, book.ask, H, thr, args.fee_bps)
        results[thr] = r
        out.append(f"| {thr} | {r.n_trades:,} | {r.hit_rate:.3f} | {r.gross_bps.mean():.4f} | {r.breakeven_fee_bps:.3f} | {r.mean_net_bps:.4f} |")
    best = max(results.values(), key=lambda r: r.breakeven_fee_bps)
    verdict = "survives" if best.breakeven_fee_bps > args.fee_bps else "does NOT survive"
    out.append(f"\nVerdict: the best variant breaks even at {best.breakeven_fee_bps:.2f} bp, so as a taker strategy it "
               f"**{verdict}** a {args.fee_bps} bp fee. A forecast this short-lived is monetised by a market maker "
               "(see section 5), not by crossing the spread.\n")

    zero = ev.taker_backtest(yhat, book.bid, book.ask, H, 0.0, 0.0)
    fees = ev.taker_backtest(yhat, book.bid, book.ask, H, 0.0, args.fee_bps)
    fig, ax = plt.subplots(figsize=(7.2, 4.0))
    ax.plot(np.cumsum(zero.gross_bps), color=SERIES[0], label="gross (mid to mid)")
    ax.plot(np.cumsum(zero.pnl_bps), color=SERIES[2], label="after half-spread")
    ax.plot(np.cumsum(fees.pnl_bps), color=SERIES[1], label=f"after half-spread + {args.fee_bps} bp fee")
    ax.axhline(0, color=INK2, lw=0.8)
    first = int(np.argmax(np.isfinite(yhat[::H])))
    ax.axvspan(0, first, color=GRID, alpha=0.5, lw=0)
    ax.text(first / 2, ax.get_ylim()[1] * 0.9, "initial training\nwindow (no trades)", ha="center", va="top",
            fontsize=8, color=INK2)
    ax.set_xlabel("holding period")
    ax.set_ylabel("cumulative P&L (bps of notional)")
    ax.set_title("Same alpha, three cost assumptions")
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIG / "alpha_costs.png", dpi=160)
    plt.close(fig)

    # --- 4. multiple testing ----------------------------------------------------
    # Every (model, threshold) variant tried at h = H is a trial. All are measured on the same
    # basis (half-spread paid, no fee) so their Sharpe ratios are comparable.
    trials = {}
    for n, fc in {**single_fc, "combined": yhat}.items():
        for thr in thresholds:
            trials[(n, thr)] = ev.taker_backtest(fc, book.bid, book.ask, H, thr, 0.0).pnl_bps
    srs = {k: v.mean() / v.std(ddof=1) for k, v in trials.items() if v.std() > 0}
    sr_var = float(np.var(list(srs.values()), ddof=1))
    best_key = max(srs, key=srs.get)
    best_pnl = trials[best_key]
    e_max = ev.expected_max_sharpe(len(srs), sr_var)
    out.append("## 4. Is the best Sharpe ratio real, given how many variants were tried?\n")
    out.append(f"Trials: {len(trials)} variants (5 models x {len(thresholds)} thresholds; {len(srs)} of them traded), "
               "each paying the half-spread, no fee. "
               f"Cross-trial variance of per-period Sharpe: {sr_var:.5f}; expected best Sharpe from pure luck: {e_max:.4f}.\n")
    out.append("| variant | per-period Sharpe | PSR (vs 0) | Deflated SR |\n|---|---|---|---|")
    out.append(f"| best: {best_key[0]}, threshold {best_key[1]} | {srs[best_key]:.4f} | "
               f"{ev.probabilistic_sharpe_ratio(best_pnl):.3f} | {ev.deflated_sharpe_ratio(best_pnl, len(srs), sr_var):.3f} |")
    fee_pnl = results[0.0].pnl_bps
    out.append(f"| combined, threshold 0, with {args.fee_bps} bp fee | {fee_pnl.mean() / fee_pnl.std(ddof=1):.4f} | "
               f"{ev.probabilistic_sharpe_ratio(fee_pnl):.3f} | — |")

    # --- 5. market making --------------------------------------------------------
    out.append("\n## 5. Monetising the alpha as a market maker (Avellaneda-Stoikov + alpha skew)\n")
    out.append("Simulated dealer, 2,000 paths, identical random numbers across strategies. Informed flow: buyers arrive "
               "faster when the drift is positive (adverse selection).\n")
    out.append("| strategy | mean P&L | sd P&L | Sharpe | sd final inventory |\n|---|---|---|---|---|")
    mm = {}
    for s in ("symmetric", "inventory", "alpha"):
        mm[s] = simulate_market_maker(s, n_sims=2000, seed=2, alpha_sd=2.0, informed=0.5).summary()
        out.append(f"| {s} | {mm[s]['mean_pnl']:.2f} | {mm[s]['std_pnl']:.2f} | {mm[s]['sharpe']:.2f} | {mm[s]['std_final_q']:.2f} |")
    weak = simulate_market_maker("alpha", n_sims=2000, seed=2, alpha_sd=2.0, informed=0.5, signal_corr=0.3).summary()
    out.append(f"| alpha, noisy signal (corr 0.3) | {weak['mean_pnl']:.2f} | {weak['std_pnl']:.2f} | {weak['sharpe']:.2f} | {weak['std_final_q']:.2f} |")

    fig, ax = plt.subplots(figsize=(7.2, 3.6))
    labels = ["symmetric", "inventory\n(Avellaneda-Stoikov)", "alpha, corr 0.3", "alpha, perfect"]
    vals = [mm["symmetric"]["sharpe"], mm["inventory"]["sharpe"], weak["sharpe"], mm["alpha"]["sharpe"]]
    ax.barh(labels, vals, color=[SERIES[1], SERIES[0], SERIES[6], SERIES[2]], height=0.6)
    for i, v in enumerate(vals):
        ax.text(v + 0.1, i, f"{v:.2f}", va="center", color=INK2, fontsize=9)
    ax.set_xlabel("Sharpe ratio of terminal P&L")
    ax.set_title("Market maker facing informed flow")
    ax.grid(axis="y", visible=False)
    fig.tight_layout()
    fig.savefig(FIG / "alpha_market_making.png", dpi=160)
    plt.close(fig)

    if null_book is not None:
        out.append("\n## 6. Control: the identical pipeline on a market with zero alpha\n")
        nsig = build_signals(null_book)
        Xn = np.column_stack([nsig[n] for n in names])
        yn = ev.forward_return_bps(null_book.mid, H)
        yhn, _ = ev.walk_forward_ridge(Xn, yn, horizon=H)
        rn = ev.taker_backtest(yhn, null_book.bid, null_book.ask, H, 0.0, 0.0)
        out.append("| statistic | planted-alpha market | zero-alpha market |\n|---|---|---|")
        out.append(f"| OOS R² | {ev.oos_r2(y, yhat):.4f} | {ev.oos_r2(yn, yhn):.4f} |")
        z0 = ev.taker_backtest(yhat, book.bid, book.ask, H, 0.0, 0.0)
        out.append(f"| break-even fee (bps) | {z0.breakeven_fee_bps:.3f} | {rn.breakeven_fee_bps:.3f} |")
        out.append(f"| PSR, half-spread paid, no fee | {ev.probabilistic_sharpe_ratio(z0.pnl_bps):.3f} | "
                   f"{ev.probabilistic_sharpe_ratio(rn.pnl_bps):.3f} |")

    path = ROOT / "docs" / "ALPHA_RESULTS.md"
    path.write_text("\n".join(out) + "\n")
    print("\n".join(out))
    print(f"\nwrote {path.relative_to(ROOT)} and docs/figures/alpha_*.png")


if __name__ == "__main__":
    main()
